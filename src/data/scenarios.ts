/** 按当前语言组装场景；切换语言整页刷新，无需缓存。 */
export function getScenarios(): Scenario[] {
  return ROWS.map(({ zh, en, ...base }) => ({
    ...base,
    title: pick(zh.title, en.title),
    hiddenNeed: pick(zh.hiddenNeed, en.hiddenNeed),
    opener: pick(zh.opener, en.opener),
    wantTags: pick(zh.wantTags, en.wantTags),
    avoidTags: pick(zh.avoidTags, en.avoidTags),
  }));
}

export function getScenarioMap(): Map<string, Scenario> {
  return new Map(getScenarios().map((s) => [s.id, s]));
}

